DROP TABLE IF EXISTS Change;
DROP TABLE IF EXISTS Task;
DROP TABLE IF EXISTS Part_in_project;
DROP TABLE IF EXISTS Role;
DROP TABLE IF EXISTS Project;
DROP TABLE IF EXISTS Change_type;
DROP TABLE IF EXISTS Status;
DROP TABLE IF EXISTS Users;

CREATE TABLE Users
(
user_id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
surname VARCHAR NOT NULL,
name VARCHAR NOT NULL,
last_name VARCHAR,
login VARCHAR NOT NULL,
password VARCHAR NOT NULL,
birthday DATE NOT NULL, 
email_adress VARCHAR NOT NULL 
); 

CREATE TABLE Status (
status_id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
name VARCHAR NOT NULL UNIQUE
);

CREATE TABLE Change_type (
type_id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
change_name VARCHAR NOT NULL UNIQUE
);

CREATE TABLE Project (
project_id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
creator_project_id INTEGER REFERENCES Users(user_id) ON DELETE SET NULL,
name VARCHAR NOT NULL,
deadline TIMESTAMP NOT NULL,
date_of_creation DATE DEFAULT CURRENT_DATE,
description TEXT
);

CREATE TABLE Role (
role_id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
role_name VARCHAR NOT NULL UNIQUE
);

CREATE TABLE Part_in_project (
participation_id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
user_id INTEGER REFERENCES Users(user_id) ON DELETE CASCADE,
role_name VARCHAR NOT NULL, 
date_add_to_project TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
project_id INTEGER REFERENCES Project(project_id) ON DELETE CASCADE,
role_id INTEGER REFERENCES Role(role_id) ON DELETE CASCADE
);

CREATE TABLE Task (
task_id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
name VARCHAR NOT NULL,
deadline TIMESTAMP NOT NULL,
creator_id INTEGER REFERENCES Users(user_id) ON DELETE SET NULL,
executor_id INTEGER REFERENCES Users(user_id) ON DELETE SET NULL,
priority INTEGER NOT NULL,
status VARCHAR NOT NULL,
description TEXT NOT NULL,
status_id INTEGER REFERENCES Status(status_id) ON DELETE SET NULL,
project_id INTEGER REFERENCES Project(project_id) ON DELETE CASCADE
);

CREATE TABLE Change (
change_id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
change_author VARCHAR NOT NULL,
user_author_id INTEGER REFERENCES Users(user_id) ON DELETE SET NULL,
type VARCHAR NOT NULL,
task_id INTEGER REFERENCES Task(task_id) ON DELETE CASCADE,
data_change TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
change_type_id INTEGER REFERENCES Change_type(type_id) ON DELETE CASCADE
);

